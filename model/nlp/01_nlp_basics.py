# ── 1. 文本预处理 ──
# 分词：jieba 中文分词（精确模式、全模式、搜索引擎模式）
# 去停用词：的、了、是、在（对分类有用，对 LLM 无意义）
# 词性标注：jieba.posseg
# 命名实体识别 (NER)：识别人名、地名、机构名

# ── 2. 文本表示（词向量之前）──
# One-hot：词表大小维，只有一个 1，稀疏且不表达语义
# TF-IDF：词频 × 逆文档频率，常用词权重低、罕见词权重高
# 词袋模型 (BoW)：忽略词序，只统计出现次数

# ── 3. Word2Vec ──
# CBOW：上下文词 → 预测中心词
# Skip-gram：中心词 → 预测上下文词（效果更好，低频词友好）
# 负采样：每次更新少量负样本而非整个词表
# 著名的类比关系：国王 - 男人 + 女人 ≈ 王后

# ── 4. RNN / LSTM 用于 NLP ──
# 文本分类：取最后时刻的 hidden state → 全连接 → softmax
# 序列标注：每个时刻输出一个标签（分词、NER）
# Seq2Seq：Encoder 编码 → Decoder 解码（机器翻译）
# Attention 出现之前：Seq2Seq + 固定长度 context vector 是瓶颈

# ── 5. 文本分类实战 ──
# 数据集：THUCNews、ChnSentiCorp（中文情感分类）
# 流程：分词 → 构建词表 → 向量化 → 模型 → 评估
# BERT 微调 vs LSTM：BERT 打 LSTM 10 个点

