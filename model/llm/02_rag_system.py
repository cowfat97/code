# ── 1. RAG 是什么 ──
# Retrieval-Augmented Generation：检索 + 生成
# 为什么需要 RAG：LLM 知识有截止日期、无法访问私有文档、会产生幻觉
# 核心流程：Query → 检索相关文档 → 拼入 Prompt → LLM 生成答案

# ── 2. 文档处理 ──
# 解析：PDF/Word/Markdown/PPT → 结构化文本
# 切分：标题作边界、表格不切、父子块（子 300 token 检索 + 父 1200 token 上下文）
# 向量化：BGE-M3 → 1024 维稠密 + 稀疏双输出

# ── 3. 检索链路 ──
# 意图分类 → 查询改写 (HyDE) → 混合检索 → 精排 (Reranker) → 生成
# 混合检索 = 稠密向量（语义）+ 稀疏向量（关键词）= WeightedRanker
# Reranker：交叉编码 vs 双编码，精度换速度

# ── 4. 评估 ──
# 检索：Recall@K、MRR
# 生成：忠程度（有没有编造）、答案相关性（有没有答所问）
# 工具：Ragas 框架 + LLM-as-Judge
# 人工抽样 5% 交叉验证，偏差 >10% 校准

# ── 5. RAG vs 长上下文 ──
# 1M token 上下文窗口为什么还要 RAG
# 大海捞针 (Needle-in-a-Haystack)：长上下文中准确率下降
# 成本：1M token 输入比检索 Top-5 贵得多
# RAG = 精准召回少量高质量上下文，不是塞满 token

