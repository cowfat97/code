# ── 1. 什么是大模型 ──
# 参数量达到 B 级别（Billion，十亿）的语言模型
# 小模型（<1B）：BERT 110M、GPT-2 124M/1.5B
# 中模型（1B-10B）：Qwen2.5-7B、LLaMA-3-8B
# 大模型（>70B）：GPT-4（1.76T）、DeepSeek-V4（~685B MoE）

# ── 2. Scaling Laws ──
# 核心发现：模型性能随参数量、数据量、计算量幂律提升
# 三个变量：N（参数量）、D（训练数据量）、C（计算量）
# Chinchilla 定律：最优配比 D ≈ 20 × N
#   例：7B 模型最优训练数据约 140B tokens
# 现实：多数模型过度训练（over-train）以提升小模型性能

# ── 3. 涌现能力 ──
# 定义：小模型没有、参数达到一定规模后突然出现的能力
# 表现：上下文学习 (ICL)、思维链 (CoT)、指令遵循
# 原因有争议：是真正的质变，还是基准的平滑增长被误读？
# 面试回答：不争论哲学问题，说"大模型在复杂推理任务上显著优于小模型"

# ── 4. LLM 训练流程 ──
# Pre-training：海量无标注文本 → 自回归预测下一个 token
# SFT（Supervised Fine-Tuning）：高质量 QA 对 → 学会对话格式
# RLHF / DPO：人类偏好数据 → 对齐人类价值观
#    RLHF：奖励模型 + PPO 强化学习（成本高）
#    DPO：直接在偏好对上优化，不需要奖励模型（简单、效果好）

# ── 5. Prompt Engineering ──
