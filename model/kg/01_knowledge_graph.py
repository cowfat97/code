# ── 1. 什么是知识图谱 ──
# 图结构存储知识：实体（节点）+ 关系（边）+ 属性
# (郝鑫磊) -[工作于]-> (法本) -[位于]-> (深圳)
# 三元组：(头实体, 关系, 尾实体) = (s, p, o)

# ── 2. 知识图谱 vs 传统数据库 ──
# 关系型：表结构，JOIN 查多跳关系慢、路径不固定时困难
# 图数据库：节点和边原生存储，多跳遍历 O(1)，适合关联分析
# 典型场景：反欺诈（关联交易网络）、推荐（用户-商品-标签）、医疗（症状-疾病-药物）

# ── 3. 知识图谱构建 ──
# 实体识别 (NER)：从文本中提取人名、地名、机构名
# 关系抽取 (RE)：判断两个实体之间是什么关系
# 实体链接：把文本中提到的"苹果"链接到 KG 里的"Apple Inc."
# 知识融合：合并多个来源的同一实体信息

# ── 4. 图数据库 Neo4j ──
# Cypher 查询语言（SQL 风格）：
#   MATCH (a:Person)-[:KNOWS]->(b:Person) RETURN a, b
# 索引：节点属性索引、全文索引
# 你的实际使用：笔记本 Docker 上有 Neo4j 容器

# ── 5. KG + LLM = Graph RAG ──
