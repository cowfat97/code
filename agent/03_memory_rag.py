# ============================================================
# Agent 复习 — 记忆 / RAG / 知识检索
# ============================================================

# ── 1. Agent 记忆系统 ──
# 会话记忆：ConversationBufferMemory、SummaryMemory
# 长期记忆：向量数据库 + 语义搜索
# 记忆提取：从对话中自动提取事实和偏好
# 语境注入：检索相关记忆 → 拼入 System Prompt

# ── 2. RAG 在 Agent 中的角色 ──
# 不是替代 LLM，是给 LLM 提供外部知识的管道
# 检索时机：工具调用（主动）vs 对话前注入（被动）
# 检索粒度：子块命中 vs 父块上下文
# knowledge base 更新：增量向量化、定期全量重建

# ── 3. 向量检索基础 ──
# Embedding 模型：BGE-M3（稠密+稀疏双输出）
# 相似度度量：余弦相似度、内积（IP）、欧氏距离
# 索引类型：IVF_FLAT（聚类加速）、HNSW（图索引）
# 向量库选型：Milvus vs pgvector vs ChromaDB

# ── 4. 混合检索 ──
# 稠密向量（语义匹配）+ 稀疏向量（关键词）= WeightedRanker
# Reranker 精排：BGE-Reranker 交叉编码
# 融合策略：加权求和 vs RRF（倒数排名融合）

