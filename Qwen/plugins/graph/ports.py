"""Structural interfaces used by the graph plugin."""

from __future__ import annotations

import builtins
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any, Literal, Protocol

from ..contracts import SearchResult, Skill


class SkillsPort(Protocol):
    def list(self) -> builtins.list[Skill]: ...
    def get(self, skill_id: str) -> Skill: ...
    def register_spec(self, spec: dict[str, Any], *, layer: str = "project") -> Skill: ...
    def search(
        self, query: str, mode: str = "keyword", limit: int = 20, filters: Any = None
    ) -> builtins.list[SearchResult]: ...
    def reload(self) -> builtins.list[Skill]: ...
    def dependencies(
        self, skill_id: str, *, recursive: bool = False
    ) -> builtins.list[Skill]: ...
    def compose_spec(self, skill_id: str) -> Any: ...
    def delete(self, skill_id: str) -> None: ...
    def export_json(self) -> str: ...
    def import_config(
        self, config: Any, *, base_path: str | Path | None = None
    ) -> builtins.list[Skill]: ...
    def save_run(self, graph_id: str, graph: dict[str, Any], state: dict[str, Any]) -> None: ...
    def load_run(self, graph_id: str) -> tuple[dict[str, Any], dict[str, Any]] | None: ...


class ToolResponse(Protocol):
    @property
    def data(self) -> Any: ...
    @property
    def content(self) -> builtins.list[dict[str, Any]]: ...
    @property
    def is_error(self) -> bool: ...


class ToolDescriptor(Protocol):
    @property
    def name(self) -> str: ...
    @property
    def description(self) -> str: ...
    @property
    def input_schema(self) -> dict[str, Any]: ...
    @property
    def output_schema(self) -> dict[str, Any] | None: ...
    @property
    def source(self) -> str: ...


class ToolsPort(Protocol):
    def list_tools(self) -> Sequence[ToolDescriptor]: ...
    async def call(
        self, name: str, arguments: dict[str, Any], timeout: float | None = None
    ) -> ToolResponse: ...


class PlanningResultPort(Protocol):
    def to_plugin_request(
        self, *, inputs: dict[str, dict[str, Any]] | None = None
    ) -> dict[str, Any]: ...

    def model_dump(self, *, mode: Literal["json"]) -> dict[str, Any]: ...


class PlannerPort(Protocol):
    async def plan(
        self,
        *,
        task: str,
        skills: Sequence[Skill],
        goal: list[str] | None = None,
        initial_conditions: list[str] | None = None,
        context: Mapping[str, Any] | None = None,
    ) -> PlanningResultPort: ...
